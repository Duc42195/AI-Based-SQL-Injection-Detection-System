"""Shared raw-data loaders for D1/D3/D4/D7, reused by both the Nhanh 1
(multiclass supervised) and Nhanh 2 (anomaly, benign-only) dataset builders.

Keeping loading logic in one place means both branches see the exact same
row-level content for a given source — important since Nhanh 2 is far more
sensitive to benign-pool noise than Nhanh 1 (see data_contract.md Muc 3.1/3.2).
"""

from __future__ import annotations

import csv
import random
import re
from pathlib import Path
from urllib.parse import unquote_plus

import pandas as pd

csv.field_size_limit(10_000_000)

_HTTP_REQUEST_LINE_RE = re.compile(r"^(GET|POST|PUT)\s+(\S+)\s+HTTP", re.MULTILINE)

# D6 (Superviz25, data_contract.md's reserved "Docker-lab/sqlmap traffic" slot
# — see report/plan/data_contract.md for how this dataset was found and why
# it fills D6 specifically): attack_technique values that map onto Branch 1's
# existing 5-class schema. `inline` (canary/fuzz-probe payloads, not a SQLi
# sub-technique) and `insider` (inspected by hand: plain session-init SQL
# like "SET NAMES utf8mb4" mislabeled as attack) are deliberately excluded —
# neither is trustworthy ground truth, so neither is loaded at all.
_D6_TECHNIQUE_TO_BRANCH1_LABEL = {
    "union": 1,
    "error": 2,
    "boolean": 3,
    "time": 4,
    "stacked": 5,
}
_D6_CHUNK_SIZE = 200_000


def load_d1(path: Path) -> list[tuple[str, bool, str]]:
    """Load D1 SQLiV3 raw rows, dropping null/empty text and duplicates.

    Returns:
        List of (raw_text, is_attack, source) tuples.
    """
    rows: list[tuple[str, bool, str]] = []
    seen: set[str] = set()
    with path.open(encoding="utf-8") as f:
        for r in csv.reader(f):
            if len(r) < 2 or r[1] not in ("0", "1"):
                continue
            text = r[0].strip()
            if not text or text in seen:
                continue
            seen.add(text)
            rows.append((text, r[1] == "1", "d1_sqliv3"))
    return rows


def load_d4(dir_path: Path) -> list[tuple[str, bool, str]]:
    """Load D4 payload-box lines (all treated as attack payloads).

    Returns:
        List of (raw_text, is_attack, source) tuples.
    """
    rows: list[tuple[str, bool, str]] = []
    seen: set[str] = set()
    for file in sorted(dir_path.glob("*.txt")):
        for line in file.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = line.strip()
            if not line or line in seen:
                continue
            seen.add(line)
            rows.append((line, True, "d4_payloadbox"))
    return rows


def load_d7(
    path: Path, normal_sample_size: int | None, seed: int
) -> list[tuple[str, bool, str]]:
    """Load D7 SR-BH 2020 attack rows (full) + a sample/all of the normal rows.

    Args:
        path: Path to data_capec_multilabel.csv.
        normal_sample_size: Max number of Normal==1 rows to sample for
            benign diversity (source dataset has 152,587 such rows). Pass
            ``None`` to keep all of them (used by the Nhanh 2 builder).
        seed: Random seed for the normal-row reservoir sample.

    Returns:
        List of (raw_text, is_attack, source) tuples.
    """
    attack_rows: list[tuple[str, bool, str]] = []
    normal_pool: list[str] = []
    rng = random.Random(seed)
    normal_seen = 0

    with path.open(encoding="utf-8", errors="replace", newline="") as f:
        reader = csv.DictReader(f)
        sqli_col = next(c for c in reader.fieldnames if "SQL Injection" in c)
        normal_col = next(c for c in reader.fieldnames if "Normal" in c)
        for row in reader:
            text = (row.get("request_http_request") or "") + " " + (row.get("request_body") or "")
            text = unquote_plus(text).strip()
            if not text:
                continue
            if row.get(sqli_col) == "1":
                attack_rows.append((text, True, "d7_srbh2020"))
            elif row.get(normal_col) == "1":
                normal_seen += 1
                if normal_sample_size is None:
                    normal_pool.append(text)
                elif len(normal_pool) < normal_sample_size:
                    normal_pool.append(text)
                else:
                    j = rng.randint(0, normal_seen - 1)
                    if j < normal_sample_size:
                        normal_pool[j] = text

    normal_rows = [(t, False, "d7_srbh2020_normal") for t in normal_pool]
    return attack_rows + normal_rows


def load_d6_superviz25(
    path: Path, seed: int, benign_cap: int, attack_cap: int
) -> list[tuple[str, bool, str, int | None]]:
    """Load D6 (Superviz25, Kaggle grgorqutel/superviz25-sql-injection-detection-dataset).

    Unlike D1/D4/D7, this source's `attack_technique` column is trusted
    DIRECTLY as the Branch-1 sub-label rather than re-derived via
    ``multiclass_tagger.tag_query``'s regex signatures. Reason: rows are
    generated by REAL sqlmap runs against a real DB with a KNOWN technique
    (ground truth by construction), and several rows are deliberately
    tamper-mangled (`tamper_method`: randomcase, multiplespaces,
    space2comment, ...) in ways that can break a hand-written regex (e.g.
    ``SLEEP\\(`` failing to match a tamper-inserted space before the paren) —
    re-tagging from content would silently corrupt exactly the evasive
    variants this source is valuable for. So the returned 4th tuple element
    is the Branch-1 label id to use AS-IS for attack rows (None for benign,
    where the caller's normal is_attack=False -> LABEL_NORMAL path applies).

    `attack_technique in {"inline", "insider"}` rows are dropped entirely, not
    loaded: `inline` is a canary/fuzz-probe payload that doesn't map to any of
    Branch 1's 5 classes; `insider` was hand-inspected and found to be plain
    session-init SQL (e.g. "SET NAMES utf8mb4") mislabeled as an attack — see
    report/plan/data_contract.md.

    The source dataset's own `split` column is IGNORED (its `train` split is
    100% benign, unusable for supervised training — see data_contract.md) in
    favor of the caller doing its own split. Attack rows carry their
    `attack_id` campaign encoded into the returned `source` string as
    ``"d6_superviz25:<attack_id>"`` (benign rows are plain
    ``"d6_superviz25"``, no campaign) so a caller can do a GROUP-aware
    train/test split — one campaign's rows (e.g. a single multi-step
    boolean-blind bisection, up to ~6,500 rows sharing a target) must never
    straddle both sides, or near-duplicate successive probe queries leak
    across the split exactly like the exact-duplicate leakage this project's
    own Branch-1 audit already found and fixed (data_contract.md, Mảng 2).

    Streamed via pandas (chunked) rather than the plain `csv` module the
    other loaders use: this file is ~1GB / 3.69M rows, far larger than D1/D3/
    D4/D7 combined, and a straight `csv.reader` pass over it is materially
    slower.

    Args:
        path: Path to data/raw/superviz25/dataset.csv.
        seed: Random seed for reservoir sampling.
        benign_cap: Max benign rows to keep (reservoir-sampled from ~3.35M).
        attack_cap: Max rows to keep PER mapped attack_technique
            (reservoir-sampled; all 5 mapped classes have far more available).

    Returns:
        List of (raw_text, is_attack, source, label_override) tuples.
    """
    rng = random.Random(seed)
    caps = {"benign": benign_cap, **{t: attack_cap for t in _D6_TECHNIQUE_TO_BRANCH1_LABEL}}
    reservoirs: dict[str, list[tuple[str, str | None]]] = {k: [] for k in caps}
    seen_counts: dict[str, int] = {k: 0 for k in caps}

    cols = ["full_query", "label", "attack_technique", "attack_id"]
    for chunk in pd.read_csv(path, usecols=cols, dtype=str, chunksize=_D6_CHUNK_SIZE):
        for label, technique, attack_id, text in zip(
            chunk["label"], chunk["attack_technique"], chunk["attack_id"], chunk["full_query"]
        ):
            if not isinstance(text, str) or not text:
                continue
            if label == "0":
                key, campaign = "benign", None
            elif technique in _D6_TECHNIQUE_TO_BRANCH1_LABEL:
                key, campaign = technique, attack_id
            else:
                continue  # inline/insider/unknown - not loaded at all
            seen_counts[key] += 1
            reservoir = reservoirs[key]
            cap = caps[key]
            if len(reservoir) < cap:
                reservoir.append((text, campaign))
            else:
                j = rng.randint(0, seen_counts[key] - 1)
                if j < cap:
                    reservoir[j] = (text, campaign)

    rows: list[tuple[str, bool, str, int | None]] = []
    for key, reservoir in reservoirs.items():
        if key == "benign":
            rows.extend((text, False, "d6_superviz25", None) for text, _ in reservoir)
        else:
            label_id = _D6_TECHNIQUE_TO_BRANCH1_LABEL[key]
            rows.extend(
                (text, True, f"d6_superviz25:{campaign}", label_id) for text, campaign in reservoir
            )
    return rows


def load_d3(path: Path, split_filter: str | None = None) -> list[tuple[str, bool, str]]:
    """Load D3 CSIC 2010 rows (wrapped raw HTTP requests) as (url, is_attack).

    Args:
        path: Path to d3_csic2010_raw.csv (see train/fetch_and_wrap_d3_csic2010.py).
        split_filter: If given, only load rows whose ``split`` column equals
            this value (e.g. ``"train"``). ``None`` loads all rows.

    Returns:
        List of (raw_text, is_attack, source) tuples. ``raw_text`` is the
        request line (method + URL) extracted from the raw HTTP block; the
        POST body, if any, is appended.
    """
    rows: list[tuple[str, bool, str]] = []
    with path.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if split_filter is not None and row.get("split") != split_filter:
                continue
            block = row.get("raw_request") or ""
            match = _HTTP_REQUEST_LINE_RE.search(block)
            if not match:
                continue
            url = match.group(2)
            # Body is whatever follows the blank-line-separated header section.
            parts = block.split("\n\n", 1)
            body = parts[1].strip() if len(parts) > 1 else ""
            text = unquote_plus(f"{url} {body}".strip())
            is_attack = row.get("label") == "anomalous"
            rows.append((text, is_attack, "d3_csic2010"))
    return rows
